// ---- worked example: four friends, five expenses ---------------------------
// The balance and transfer logic mirrors calcSettlement in TripPlan.jsx: each
// expense is split equally between its participants, balances are paid minus
// share, and the largest creditor is matched against the largest debtor. The
// numbers below are computed here, not typed, so the tables cannot drift apart.
type Person = "dana" | "yoni" | "maya" | "omer";
const NAMES: Record<Person, string> = { dana: "דנה", yoni: "יוני", maya: "מאיה", omer: "עומר" };
const PEOPLE = Object.keys(NAMES) as Person[];

const EXPENSES: { what: string; payer: Person; amount: number; among: Person[]; amongLabel: string }[] = [
  { what: "דירה לארבעה לילות", payer: "dana", amount: 480, among: PEOPLE, amongLabel: "כולם" },
  { what: "השכרת רכב ודלק", payer: "yoni", amount: 200, among: PEOPLE, amongLabel: "כולם" },
  { what: "ארוחת ערב", payer: "maya", amount: 120, among: PEOPLE, amongLabel: "כולם" },
  { what: "קניות בסופר", payer: "omer", amount: 60, among: PEOPLE, amongLabel: "כולם" },
  { what: "הפלגה בסירה", payer: "dana", amount: 90, among: ["dana", "maya", "omer"], amongLabel: "דנה, מאיה ועומר (יוני לא הצטרף)" },
];

function computeExample() {
  const paid = Object.fromEntries(PEOPLE.map((p) => [p, 0])) as Record<Person, number>;
  const share = Object.fromEntries(PEOPLE.map((p) => [p, 0])) as Record<Person, number>;
  for (const e of EXPENSES) {
    paid[e.payer] += e.amount;
    for (const p of e.among) share[p] += e.amount / e.among.length;
  }
  const bal = Object.fromEntries(PEOPLE.map((p) => [p, paid[p] - share[p]])) as Record<Person, number>;
  const pos = PEOPLE.filter((p) => bal[p] > 0.01).map((p) => ({ p, b: bal[p] })).sort((a, b) => b.b - a.b);
  const neg = PEOPLE.filter((p) => bal[p] < -0.01).map((p) => ({ p, b: bal[p] })).sort((a, b) => a.b - b.b);
  const transfers: { from: Person; to: Person; amount: number }[] = [];
  let i = 0;
  let j = 0;
  while (i < pos.length && j < neg.length) {
    const amt = Math.min(pos[i].b, -neg[j].b);
    if (amt > 0.01) transfers.push({ from: neg[j].p, to: pos[i].p, amount: amt });
    pos[i].b -= amt;
    neg[j].b += amt;
    if (Math.abs(pos[i].b) < 0.01) i++;
    if (Math.abs(neg[j].b) < 0.01) j++;
  }
  const total = EXPENSES.reduce((s, e) => s + e.amount, 0);
  return { paid, share, bal, transfers, total };
}

